// Builds skills/kovan/scripts/kovan.mjs: one self-contained Node file with the
// SDK, the deployment record, and the local wallet page (its browser script
// and styles inlined). Run from signer/: npm run build:cli
import { readFile } from "node:fs/promises";
import { build } from "esbuild";

const here = (p) => new URL(p, import.meta.url).pathname;
const outfile = here("../../skills/kovan/scripts/kovan.mjs");

const pageJs = await build({
  entryPoints: [here("../src/wallet-page.ts")],
  bundle: true, write: false, format: "iife", platform: "browser", target: "es2020", minify: true, legalComments: "none",
});

// Inline the same locally hosted fonts as the static signer. The generated
// wallet page stays self-contained, including its typography and license.
const pageCss = await build({
  entryPoints: [here("../src/style.css")],
  bundle: true, write: false, loader: { ".woff2": "dataurl" }, minify: true,
});
const fontLicense = await readFile(here("../src/fonts/OFL.txt"), "utf8");

await build({
  entryPoints: [here("../src/cli.ts")],
  outfile,
  bundle: true, format: "esm", platform: "node", target: "node20", minify: false, legalComments: "none",
  // Node has Buffer built in; the browser polyfill is not needed (and warns on Node).
  alias: { buffer: "node:buffer" },
  // Some bundled CommonJS dependencies call require(); give ESM output one.
  // The SDK's base32 dependency uses the deprecated Buffer() constructor; keep agents' stderr clean.
  banner: { js: "#!/usr/bin/env node\n// Generated by signer/scripts/build-cli.mjs from signer/src/cli.ts. Do not edit.\nimport { createRequire as __kovanRequire } from 'node:module'; const require = __kovanRequire(import.meta.url);\nprocess.noDeprecation = true;" },
  define: {
    __KOVAN_BUNDLE__: "true",
    __WALLET_PAGE_JS__: JSON.stringify(pageJs.outputFiles[0].text),
    __WALLET_PAGE_CSS__: JSON.stringify(`/* ${fontLicense} */\n${pageCss.outputFiles[0].text}`),
  },
  logLevel: "warning",
});
console.log(`built ${outfile}`);
